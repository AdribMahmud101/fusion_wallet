#!/usr/bin/env python3
"""Generate Android session signatures from the contract ABI and copy the real app test vector.

Run from any directory; --check verifies committed outputs without writing them.
Rust reads the authoritative Solidity interface directly with alloy::sol!.
"""
import argparse
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'scripts'))
from keccak256 import keccak256_hex


def outputs():
    abi = json.loads(subprocess.check_output([
        'forge', 'inspect', '--root', str(ROOT / 'src/contracts'),
        'src/IKavachiModule.sol:IKavachiModule', 'abi', '--json'], text=True))

    def canonical(arg):
        if arg['type'].startswith('tuple'):
            return '(' + ','.join(map(canonical, arg['components'])) + ')' + arg['type'][5:]
        return arg['type']

    functions = [next(f for f in abi if f.get('type') == 'function' and f['name'] == name)
                 for name in ('execute', 'queueAction')]
    signatures = [f['name'] + '(' + ','.join(map(canonical, f['inputs'])) + ')' for f in functions]
    app = ROOT / 'src/Fintech_Wallet_Agent/fusion-core-android/app/src'
    kotlin = ('package app.fusion.wallet.agent\n\n'
              '// Generated by scripts/android_planner/generate_session_allowlist.py from\n'
              '// src/contracts/src/IKavachiModule.sol ABI. Do not edit selectors by hand.\n'
              'internal object SessionEntryPoints {\n    val selectors = setOf(\n')
    kotlin += ',\n'.join(f'        "{keccak256_hex(sig.encode())[:10]}", // {sig}' for sig in signatures)
    kotlin += '\n    )\n}\n'
    golden = json.loads((ROOT / 'evidence/app/agent/golden_app.json').read_text())[0]
    vector = json.loads((ROOT / golden['transaction']).read_text())
    vector['decisionHash'] = golden['decisionHash']
    return {
        app / 'main/java/app/fusion/wallet/agent/SessionEntryPoints.kt': kotlin,
        app / 'test/resources/golden_app_transaction.json': json.dumps(vector, indent=2) + '\n',
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            assert path.read_text() == content, f'Stale generated file: {path}'
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
