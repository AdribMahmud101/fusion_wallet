#!/usr/bin/env bash
# Reproducible Android wrapper + fork packaging; never packages the model.
set -euo pipefail
ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
source /root/projects/fusion_wallet/scripts/edge_android_env.sh
if ! rustc --version >/dev/null 2>&1 && [[ -d /root/.auth_pool/antigravity_1/.rustup/toolchains ]]; then
  export RUSTUP_HOME=/root/.auth_pool/antigravity_1/.rustup
fi
FORK=${MNN_ANDROID_BUILD:-/root/projects/victor_fusion/ahem/third_party/MNN/build_a64_qnn}
MODEL=${FUSION_MODEL_DIR:-/root/projects/feros/sdk/demo-app/app/src/main/assets/models/lfm_230m}
APP="$ROOT/src/Fintech_Wallet_Agent/fusion-core-android/app"
DEST="$APP/src/main/jniLibs/arm64-v8a"
mkdir -p "$DEST"
cargo build --manifest-path "$ROOT/src/fusion-planner/android/Cargo.toml" --target aarch64-linux-android --release --locked
cp "$ROOT/src/fusion-planner/android/target/aarch64-linux-android/release/libfusion_planner_android.so" "$DEST/"
# Default: the published, hash-verified fork libraries. Rebuilding libllm from the
# fork source is not byte-reproducible (every rebuild changes its hash), so source
# builds are opt-in: FORCE_FORK_BUILD=1 with a local fork tree, then re-pin.
if [[ "${FORCE_FORK_BUILD:-0}" == 1 && -d "$FORK" ]]; then
  # Local fork build tree: package from source (patched libllm rebuilt).
  cp "$FORK/OFF/arm64-v8a/libMNN.so" "$DEST/"
  python3 "$ROOT/scripts/android_planner/rebuild_llm.py"
  cp "$ROOT/src/fusion-planner/android/target/mnn-patched/libllm.so" "$DEST/"
  cp "$FORK/express/OFF/arm64-v8a/libMNN_Express.so" "$DEST/"
  cp "$FORK/source/backend/opencl/OFF/arm64-v8a/libMNN_CL.so" "$DEST/"
  cp "$FORK/source/backend/vulkan/OFF/arm64-v8a/libMNN_Vulkan.so" "$DEST/"
  llvm-strip --strip-unneeded "$DEST/"*.so
else
  # Fresh clone: install the published, hash-verified fork libraries.
  bash "$ROOT/scripts/android_planner/fetch_prebuilt.sh" "$DEST"
  llvm-strip --strip-unneeded "$DEST/libfusion_planner_android.so"
fi
if [[ "${FORCE_FORK_BUILD:-0}" == 1 && -d "$MODEL" ]]; then
python3 - "$MODEL" "$DEST" "$APP/src/main/java/app/fusion/wallet/inference/ProvisionedHashes.kt" <<'PY'
import hashlib,json,pathlib,sys
model,libs,out=map(pathlib.Path,sys.argv[1:])
hashes={}
for root,names in [(model,['config.json','llm_config.json','llm.mnn','llm.mnn.weight','tokenizer.mtok']),
                   (libs,['libMNN.so','libllm.so','libMNN_Express.so','libMNN_CL.so','libMNN_Vulkan.so'])]:
    for name in names:
        hashes[name]=hashlib.file_digest((root/name).open('rb'),'sha256').hexdigest()
out.write_text('package app.fusion.wallet.inference\n\n// Generated by scripts/android_planner/build.sh from provisioned assets. No model bytes.\ninternal object ProvisionedHashes {\n    const val JSON = """'+json.dumps(hashes,sort_keys=True,separators=(',',':'))+'"""\n}\n')
print('Pinned model and fork hashes; model stays outside APK.')
PY
else
  echo "Model files not present locally: keeping the committed ProvisionedHashes.kt (it pins the published libraries)."
fi
